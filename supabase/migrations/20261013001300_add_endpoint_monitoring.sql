alter table public.assets
  add constraint assets_id_mosque_unique unique (id, mosque);

create table public.endpoint_devices (
  id uuid primary key default gen_random_uuid(),
  asset_id uuid not null unique,
  client_name text not null references public.helpdesk_clients (name) on update cascade on delete restrict,
  hostname text not null check (char_length(hostname) between 1 and 255),
  operating_system text not null check (char_length(operating_system) between 1 and 80),
  agent_version text check (agent_version is null or char_length(agent_version) <= 64),
  is_active boolean not null default true,
  token_hash text not null unique check (token_hash ~ '^[0-9a-f]{64}$'),
  last_seen_at timestamptz,
  cpu_percent numeric(5,2) check (cpu_percent is null or cpu_percent between 0 and 100),
  memory_percent numeric(5,2) check (memory_percent is null or memory_percent between 0 and 100),
  disk_percent numeric(5,2) check (disk_percent is null or disk_percent between 0 and 100),
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  constraint endpoint_devices_asset_client_fkey
    foreign key (asset_id, client_name)
    references public.assets (id, mosque)
    on update cascade on delete cascade
);

create index endpoint_devices_client_name_idx on public.endpoint_devices (client_name);
create index endpoint_devices_last_seen_idx on public.endpoint_devices (last_seen_at desc);

alter table public.endpoint_devices enable row level security;
revoke all on table public.endpoint_devices from anon, authenticated;
grant select (
  id, asset_id, client_name, hostname, operating_system, agent_version,
  is_active, last_seen_at, cpu_percent, memory_percent, disk_percent,
  created_by, created_at
) on table public.endpoint_devices to authenticated;
grant insert (asset_id, client_name, hostname, operating_system, token_hash, created_by)
  on table public.endpoint_devices to authenticated;
grant update (is_active) on table public.endpoint_devices to authenticated;

create policy "Designated staff can view monitored devices"
  on public.endpoint_devices
  for select
  to authenticated
  using (
    exists (
      select 1 from public.helpdesk_staff as staff
      where staff.user_id = (select auth.uid())
    )
  );

create policy "Designated staff can enroll monitored devices"
  on public.endpoint_devices
  for insert
  to authenticated
  with check (
    created_by = (select auth.uid())
    and exists (
      select 1 from public.helpdesk_staff as staff
      where staff.user_id = (select auth.uid())
    )
  );

create policy "Designated staff can activate or pause monitoring"
  on public.endpoint_devices
  for update
  to authenticated
  using (
    exists (
      select 1 from public.helpdesk_staff as staff
      where staff.user_id = (select auth.uid())
    )
  )
  with check (
    exists (
      select 1 from public.helpdesk_staff as staff
      where staff.user_id = (select auth.uid())
    )
  );

create table public.endpoint_heartbeats (
  id bigint generated by default as identity primary key,
  device_id uuid not null references public.endpoint_devices (id) on delete cascade,
  checked_at timestamptz not null default now(),
  cpu_percent numeric(5,2) check (cpu_percent is null or cpu_percent between 0 and 100),
  memory_percent numeric(5,2) check (memory_percent is null or memory_percent between 0 and 100),
  disk_percent numeric(5,2) check (disk_percent is null or disk_percent between 0 and 100),
  agent_version text check (agent_version is null or char_length(agent_version) <= 64)
);

create index endpoint_heartbeats_device_checked_idx
  on public.endpoint_heartbeats (device_id, checked_at desc);

alter table public.endpoint_heartbeats enable row level security;
revoke all on table public.endpoint_heartbeats from anon, authenticated;
grant select on table public.endpoint_heartbeats to authenticated;

create policy "Designated staff can view endpoint history"
  on public.endpoint_heartbeats
  for select
  to authenticated
  using (
    exists (
      select 1 from public.helpdesk_staff as staff
      where staff.user_id = (select auth.uid())
    )
  );
